"""Turn the pet's unfurl videos into sprite sheets the app can play.

Each video shows the armadillo going from the curled ball to one stage's pose,
on flat green, framed so the poses sit at their in-app sizes on one ground line
(see FRAME below). This cuts the still lead-in and tail, picks evenly spaced
frames, removes the green, and packs the frames into one PNG per stage.

    python scripts/build_pet_clips.py --src <folder with unfurl-s2.mp4 ... unfurl-s5.mp4> [--sheet out.png]

Writes assets/pet/clips/unfurl_s<stage>.png and constants/petClips.ts.
Needs ffmpeg on PATH.
"""

from __future__ import annotations

import argparse
import subprocess
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

from key_pet_poses import key_out

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "assets" / "pet" / "clips"
TS_PATH = ROOT / "constants" / "petClips.ts"

# How the video was framed, as fractions of its width: the pet's box (the same
# box the app draws a pose in) is BOX wide, centred, with its bottom at BOTTOM.
BOX = 760 / 1024
BOTTOM = 922 / 1024
# A frame keeps a little room around the box for stretches and bounces.
CELL_SCALE = 1.2  # frame side, in boxes
CELL_DROP = 0.04  # how far the frame extends below the box bottom, in boxes

CELL_PX = 400
COLS = 6
MAX_FRAMES = {2: 18, 3: 24, 4: 36, 5: 36}
STILL = 2.2  # mean absolute difference below which two frames count as the same


def extract(video: Path, folder: Path) -> list[Path]:
    subprocess.run(
        ["ffmpeg", "-v", "error", "-y", "-i", str(video), str(folder / "f%04d.png")],
        check=True,
    )
    return sorted(folder.glob("f*.png"))


def cell_box(width: int) -> tuple[int, int, int, int]:
    box = BOX * width
    side = CELL_SCALE * box
    bottom = BOTTOM * width + CELL_DROP * box
    left = (width - side) / 2
    return (round(left), round(bottom - side), round(left + side), round(bottom))


def active_range(frames: list[np.ndarray]) -> tuple[int, int]:
    """Drop frames that are still the opening pose, and frames already on the last pose."""
    first, last = frames[0].astype(np.int16), frames[-1].astype(np.int16)
    start = 0
    while start + 1 < len(frames) and np.abs(frames[start + 1].astype(np.int16) - first).mean() < STILL:
        start += 1
    end = len(frames) - 1
    while end - 1 > start and np.abs(frames[end - 1].astype(np.int16) - last).mean() < STILL:
        end -= 1
    return start, end


def build(stage: int, video: Path) -> tuple[Image.Image, int, int]:
    with tempfile.TemporaryDirectory() as tmp:
        paths = extract(video, Path(tmp))
        images = [Image.open(p).convert("RGB") for p in paths]
    crop = cell_box(images[0].width)
    cells = [im.crop(crop) for im in images]
    small = [np.array(c.resize((96, 96))) for c in cells]
    start, end = active_range(small)
    count = min(MAX_FRAMES[stage], end - start + 1)
    picks = [round(start + i * (end - start) / (count - 1)) for i in range(count)]
    rows = (count + COLS - 1) // COLS
    sheet = Image.new("RGBA", (COLS * CELL_PX, rows * CELL_PX), (0, 0, 0, 0))
    for i, idx in enumerate(picks):
        frame = key_out(cells[idx]).resize((CELL_PX, CELL_PX), Image.LANCZOS)
        sheet.alpha_composite(frame, ((i % COLS) * CELL_PX, (i // COLS) * CELL_PX))
    print(f"stage {stage}: {len(images)} video frames, active {start}..{end}, kept {count}")
    return sheet, count, rows


def write_ts(clips: dict[int, tuple[int, int]]) -> None:
    lines = [
        "// Generated by scripts/build_pet_clips.py. Do not edit by hand.",
        "import type { ImageSourcePropType } from 'react-native';",
        "",
        "/** A frame-by-frame clip packed into one image, read left to right, top to bottom. */",
        "export type PetClip = {",
        "  source: ImageSourcePropType;",
        "  frames: number;",
        "  cols: number;",
        "  rows: number;",
        "};",
        "",
        "/** A frame is this many pet boxes wide and tall, centred on the box. */",
        f"export const PET_CLIP_SCALE = {CELL_SCALE};",
        "/** How far a frame hangs below the bottom of the pet box, in boxes. */",
        f"export const PET_CLIP_DROP = {CELL_DROP};",
        "",
        "/** The curled ball opening into each stage's idle pose. Play backwards to curl up. */",
        "export const PET_UNFURL_CLIPS: Record<2 | 3 | 4 | 5, PetClip> = {",
    ]
    for stage, (count, rows) in sorted(clips.items()):
        lines.append(
            f"  {stage}: {{ source: require('../assets/pet/clips/unfurl_s{stage}.png'), "
            f"frames: {count}, cols: {COLS}, rows: {rows} }},"
        )
    lines += ["};", ""]
    TS_PATH.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--src", required=True, type=Path)
    parser.add_argument("--sheet", type=Path, help="Optional preview of every clip on forest green")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    clips: dict[int, tuple[int, int]] = {}
    previews: list[Image.Image] = []
    for stage in (2, 3, 4, 5):
        video = args.src / f"unfurl-s{stage}.mp4"
        if not video.exists():
            raise SystemExit(f"Missing {video}")
        sheet, count, rows = build(stage, video)
        out = OUT_DIR / f"unfurl_s{stage}.png"
        # Flat-colour art: a palette keeps the file small with no visible change.
        sheet.quantize(colors=160, method=Image.Quantize.FASTOCTREE).save(out, optimize=True)
        print(f"  -> {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
        clips[stage] = (count, rows)
        previews.append(sheet)
    write_ts(clips)

    if args.sheet:
        scale = 0.3
        width = max(p.width for p in previews)
        height = sum(p.height for p in previews)
        board = Image.new("RGBA", (width, height), (62, 107, 78, 255))
        y = 0
        for p in previews:
            board.alpha_composite(p, (0, y))
            y += p.height
        board = board.resize((round(width * scale), round(height * scale)), Image.LANCZOS)
        board.convert("RGB").save(args.sheet)


if __name__ == "__main__":
    main()
